#!/usr/bin/env bash
# setup-gateway.sh — Configure macOS/Linux as a captive portal gateway
# Usage: sudo bash setup-gateway.sh [PORTAL_IP] [INTERFACE]
set -euo pipefail

PORTAL_IP="${1:-$(ipconfig getifaddr en0 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}' || echo '192.168.1.1')}"
IFACE="${2:-en0}"

echo "========================================="
echo "  Free Wi-Fi Captive Portal Gateway Setup"
echo "========================================="
echo "Portal IP:  $PORTAL_IP"
echo "Interface:  $IFACE"
echo ""

# Step 1: Enable IP forwarding
echo "[1/4] Enabling IP forwarding..."
if [[ "$(uname)" == "Darwin" ]]; then
  sysctl -w net.inet.ip.forwarding=1
else
  sysctl -w net.ipv4.ip_forward=1
  echo 1 > /proc/sys/net/ipv4/ip_forward
fi

# Step 2: Generate pf.conf for macOS
if [[ "$(uname)" == "Darwin" ]]; then
  echo "[2/4] Generating pf rules (portal.conf)..."
  cat > portal.conf <<CONF
# Free Wi-Fi Captive Portal - PF Rules
# Generated by setup-gateway.sh

# Table for authenticated clients
table <allowed_wifi> persist

# Redirect HTTP (port 80) from unauthenticated clients to portal
rdr pass on $IFACE inet proto tcp from !<allowed_wifi> to any port 80 -> $PORTAL_IP port 3000

# Allow authenticated clients full internet
pass out quick inet from <allowed_wifi> to any keep state

# Allow DNS (needed for captive portal detection)
pass out quick inet proto udp from any to any port 53 keep state
pass out quick inet proto tcp from any to any port 53 keep state

# Allow traffic to portal itself
pass in quick inet proto tcp from any to $PORTAL_IP port 3000 keep state

# Block all other outbound from unauthenticated clients
block out quick inet from any to any
CONF

  echo "[3/4] Loading pf rules..."
  pfctl -f ./portal.conf
  pfctl -e 2>/dev/null || true

  echo "[4/4] Done!"
  echo ""
  echo "Portal running at: http://$PORTAL_IP:3000/portal"
  echo ""
  echo "Commands:"
  echo "  Start server:    node server.js"
  echo "  Start DNS:       sudo node dns-captive.js $PORTAL_IP"
  echo "  Disable firewall: sudo pfctl -d"
  echo "  Show allowed IPs: sudo pfctl -t allowed_wifi -T show"

else
  # Linux iptables fallback
  echo "[2/4] Setting up iptables rules..."
  
  # Flush existing portal rules
  iptables -t nat -F PREROUTING 2>/dev/null || true
  
  # Redirect port 80 to portal for unauthenticated clients
  iptables -t nat -A PREROUTING -i "$IFACE" -p tcp --dport 80 -j DNAT --to-destination "$PORTAL_IP:3000"
  
  # Create allowed chain
  iptables -N WIFI_ALLOWED 2>/dev/null || iptables -F WIFI_ALLOWED
  iptables -A FORWARD -j WIFI_ALLOWED
  
  # NAT for outbound
  iptables -t nat -A POSTROUTING -o "$IFACE" -j MASQUERADE
  
  echo "[3/4] iptables rules applied."
  echo "[4/4] Done!"
  echo ""
  echo "Portal running at: http://$PORTAL_IP:3000/portal"
  echo ""
  echo "Commands:"
  echo "  Start server:    node server.js"
  echo "  Start DNS:       sudo node dns-captive.js $PORTAL_IP"
  echo "  Allow IP:        iptables -A WIFI_ALLOWED -s <IP> -j ACCEPT"
  echo "  Revoke IP:       iptables -D WIFI_ALLOWED -s <IP> -j ACCEPT"
fi
